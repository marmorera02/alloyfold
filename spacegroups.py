# -*- coding: utf-8 -*-
# engine/spacegroups.py
#
# Space-group symmetry operations for crystal structure generation.
#
# Each group is defined by a few generator operations in International
# Tables notation ('-x,y+1/2,-z+1/2'); the full group of general-position
# operations is built by closing the generators under multiplication.
#
# The groups listed cover roughly 90% of organic molecular crystals
# (frequencies are approximate CSD statistics, used as sampling weights).
#
# Convention: fractional coordinates are column vectors, an operation
# (W, w) maps s -> W s + w (mod 1).

import re
import numpy as np
from typing import List, Tuple

Op = Tuple[np.ndarray, np.ndarray]   # (W 3x3 int, w 3 float)


def parse_op(text: str) -> Op:
    """'-x+1/2,y,-z' -> (W, w)."""
    W = np.zeros((3, 3), int)
    w = np.zeros(3)
    for row, part in enumerate(text.replace(' ', '').split(',')):
        for sign, tok in re.findall(r'([+-]?)(x|y|z|\d+/\d+|\d+)', part):
            s = -1 if sign == '-' else 1
            if tok in 'xyz':
                W[row, 'xyz'.index(tok)] = s
            elif '/' in tok:
                num, den = tok.split('/')
                w[row] += s * int(num) / int(den)
            else:
                w[row] += s * int(tok)
    return W, w % 1.0


def _key(op: Op):
    W, w = op
    return (tuple(W.ravel()), tuple(np.round(w % 1.0, 6) % 1.0))


def close_group(generators: List[str]) -> List[Op]:
    """All operations generated by the given generators (incl. identity)."""
    ops = {_key((np.eye(3, dtype=int), np.zeros(3)))}
    group = [(np.eye(3, dtype=int), np.zeros(3))]
    gens = [parse_op(g) for g in generators]
    frontier = list(group)
    while frontier:
        new = []
        for W1, w1 in frontier:
            for W2, w2 in gens:
                op = (W2 @ W1, (W2 @ w1 + w2) % 1.0)
                k = _key(op)
                if k not in ops:
                    ops.add(k)
                    group.append(op)
                    new.append(op)
        frontier = new
        if len(group) > 192:
            raise ValueError('generators do not close to a space group')
    return group


# name: (generators, crystal system, approx. CSD frequency)
SPACE_GROUPS = {
    'P1':      ([],                                              'triclinic',    0.010),
    'P-1':     (['-x,-y,-z'],                                    'triclinic',    0.250),
    'P21':     (['-x,y+1/2,-z'],                                 'monoclinic',   0.050),
    'C2':      (['-x,y,-z', 'x+1/2,y+1/2,z'],                    'monoclinic',   0.010),
    'Cc':      (['x,-y,z+1/2', 'x+1/2,y+1/2,z'],                 'monoclinic',   0.010),
    'P21/c':   (['-x,y+1/2,-z+1/2', '-x,-y,-z'],                 'monoclinic',   0.340),
    'C2/c':    (['-x,y,-z+1/2', '-x,-y,-z', 'x+1/2,y+1/2,z'],    'monoclinic',   0.080),
    'P212121': (['-x+1/2,-y,z+1/2', '-x,y+1/2,-z+1/2'],          'orthorhombic', 0.070),
    'Pna21':   (['-x,-y,z+1/2', 'x+1/2,-y+1/2,z'],               'orthorhombic', 0.015),
    'Pbca':    (['-x+1/2,-y,z+1/2', '-x,y+1/2,-z+1/2', '-x,-y,-z'],
                                                                 'orthorhombic', 0.035),
    # Reference only (CO2 Pa-3); not sampled by default.
    'Pa-3':    (['-x+1/2,-y,z+1/2', '-x,y+1/2,-z+1/2', 'z,x,y', '-x,-y,-z'],
                                                                 'cubic',        0.0),
}

_CACHE = {}


def operations(name: str) -> List[Op]:
    if name not in _CACHE:
        _CACHE[name] = close_group(SPACE_GROUPS[name][0])
    return _CACHE[name]


def crystal_system(name: str) -> str:
    return SPACE_GROUPS[name][1]


def sampling_weights(names: List[str] = None) -> Tuple[List[str], np.ndarray]:
    names = names or [n for n, v in SPACE_GROUPS.items() if v[2] > 0]
    p = np.array([SPACE_GROUPS[n][2] for n in names], float)
    return names, p / p.sum()


def inversion_centres(name: str) -> List[np.ndarray]:
    """Fractional positions of the inversion centres of the group
    (one per inversion operation, i.e. at w/2 for W = -I)."""
    out = []
    for W, w in operations(name):
        if np.array_equal(W, -np.eye(3, dtype=int)):
            out.append((w / 2.0) % 1.0)
    return out


if __name__ == '__main__':
    for n in SPACE_GROUPS:
        print(f'{n:<8} {crystal_system(n):<12} order={len(operations(n)):>3}'
              f'  inversion centres={len(inversion_centres(n))}')
